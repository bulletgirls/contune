package crash

import (
	"reflect"
	"testing"
)

func TestParseGDB(t *testing.T) {
	// gdb 15(-O2 -g, frame-info location-and-address)의 실제 출력과 옛 gdb·특수 칸 모양.
	out := `[New LWP 3975]
[Thread debugging using libthread_db enabled]
Core was generated by ` + "`../prog a'" + `.
Program terminated with signal SIGABRT, Aborted.
#0  __pthread_kill_implementation (no_tid=0, signo=6, threadid=<optimized out>) at ./nptl/pthread_kill.c:44
44	./nptl/pthread_kill.c: No such file or directory.
--eum-bt--
#0  0x00007efca949ec0c in __pthread_kill_implementation (no_tid=..., signo=..., threadid=...) at ./nptl/pthread_kill.c:44
#1  0x00007efca949ec0c in __pthread_kill_internal (signo=..., threadid=...) at ./nptl/pthread_kill.c:78
#2  __GI___pthread_kill (threadid=..., signo=...) at ./nptl/pthread_kill.c:89
#3  0x00007efca944527e in __GI_raise (sig=...) at ../sysdeps/posix/raise.c:26
#4  0x00007efca94288ff in ?? () from /lib/x86_64-linux-gnu/libc.so.6
#5  0x000055d02ad7d126 in check_book (...)
#6  <signal handler called>
#7  0x0000000000401136 in std::function<void (int)>::operator() (this=..., __args#0=...) at /usr/include/c++/13/bits/std_function.h:591
#8  0x0000000000401200 in (anonymous namespace)::run () at main.cc:7
#9  0x0000000000401300 in main ()
Backtrace stopped: previous frame inner to this frame (corrupt stack?)
(More stack frames follow...)
`
	frames, notes := parseGDB(out)
	want := []gdbFrame{
		{num: 0, addr: 0x7efca949ec0c, hasAddr: true, fn: "__pthread_kill_implementation", file: "./nptl/pthread_kill.c", line: 44},
		{num: 1, addr: 0x7efca949ec0c, hasAddr: true, fn: "__pthread_kill_internal", file: "./nptl/pthread_kill.c", line: 78},
		{num: 2, fn: "__GI___pthread_kill", file: "./nptl/pthread_kill.c", line: 89},
		{num: 3, addr: 0x7efca944527e, hasAddr: true, fn: "__GI_raise", file: "../sysdeps/posix/raise.c", line: 26},
		{num: 4, addr: 0x7efca94288ff, hasAddr: true, fn: "??", lib: "/lib/x86_64-linux-gnu/libc.so.6"},
		{num: 5, addr: 0x55d02ad7d126, hasAddr: true, fn: "check_book"},
		{num: 6, fn: "<signal handler called>"},
		{num: 7, addr: 0x401136, hasAddr: true, fn: "std::function<void (int)>::operator()", file: "/usr/include/c++/13/bits/std_function.h", line: 591},
		{num: 8, addr: 0x401200, hasAddr: true, fn: "(anonymous namespace)::run", file: "main.cc", line: 7},
		{num: 9, addr: 0x401300, hasAddr: true, fn: "main"},
	}
	if !reflect.DeepEqual(frames, want) {
		t.Fatalf("frames =\n%+v\nwant\n%+v", frames, want)
	}
	if len(notes) != 1 || notes[0] != "gdb: Backtrace stopped: previous frame inner to this frame (corrupt stack?)" {
		t.Fatalf("notes = %q", notes)
	}

	// 표식이 없으면(옛 출력) 마지막 #0부터 다시 센다: 처음 core를 열 때 찍은 #0을 겹치지 않는다.
	old := `#0  book_insert (b=0x0, v=v@entry=2) at prog.c:12
12		nd->v = v;
#0  book_insert (b=0x0, v=v@entry=2) at prog.c:12
#1  0x000055e9adb6333f in process_order (b=b@entry=0x0, v=v@entry=2) at prog.c:19
`
	frames, _ = parseGDB(old)
	if len(frames) != 2 || frames[0].fn != "book_insert" || frames[0].hasAddr || frames[1].fn != "process_order" || frames[1].line != 19 {
		t.Fatalf("old = %+v", frames)
	}
	if f, _ := parseGDB("No symbol table is loaded.\n"); len(f) != 0 {
		t.Fatalf("빈 출력 = %+v", f)
	}
}

func TestGDBArgs(t *testing.T) {
	got := gdbArgs("/srv/bin/svc", "/srv/core", 32)
	want := []string{"-batch", "-nx", "-iex", "set auto-load off", "-iex", "set debuginfod enabled off",
		"-ex", "set pagination off", "-ex", "set print frame-arguments none", "-ex", "set print frame-info location-and-address",
		"-ex", `echo --eum-bt--\n`, "-ex", "bt 32", "/srv/bin/svc", "-c", "/srv/core"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("gdbArgs = %q", got)
	}
	if got := gdbArgs("", "/c", 5); got[len(got)-2] != "-c" || got[len(got)-3] != "bt 5" {
		t.Fatalf("exe 없음 = %q", got)
	}
}
